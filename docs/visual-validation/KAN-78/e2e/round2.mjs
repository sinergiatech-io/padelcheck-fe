// KAN-78 round 2: draft without registration window, Combinado 6ta + 6ta, readable names from the API,
// custom names kept, and browser Back held while the confirmation is in flight.
import assert from 'node:assert/strict'
import { open, login, steps1to3, shot, label, db, BASE } from './lib.mjs'
const NAME = 'Copa Mixta ' + (Date.now() % 100000)
const { browser, page } = await open()
await login(page, 'admin@kan78.test')
// Enter the wizard in-app (client-side navigation), as an organizer does from «Eventos»
await page.goto(BASE + '/club/events')
await page.getByRole('button', { name: 'Crear evento' }).click(); await page.waitForURL(/\/club\/events\/new$/)
await steps1to3(page, NAME, false)
// Step 4: Combinado with the same category twice
await label(page, 'Mixto').click(); await label(page, 'Combinado').click()
await page.getByLabel(/Categoría A/).selectOption({ label: '6ta' }); await page.getByLabel(/Categoría B/).selectOption({ label: '6ta' })
assert.equal(await page.getByText('Completá la combinación').count(), 0)
await shot(page, '60-step4-combinado-same-twice', true)
await page.getByRole('button', { name: 'Continuar' }).click()
await page.getByLabel('Máximo de parejas').fill('8'); await page.getByLabel('Sí, admitir lista de espera').check()
await page.getByRole('button', { name: 'Continuar' }).click()
await page.getByText('Mixto · 6ta + 6ta').waitFor()
// Second division: Suma 13 Caballeros
await page.getByRole('button', { name: 'Agregar división' }).click()
await label(page, 'Suma').click(); await page.getByLabel('Suma de categorías').fill('13')
await page.getByRole('button', { name: 'Continuar' }).click()
await page.getByLabel('Máximo de parejas').fill('16'); await page.getByLabel('No, cerrar al completar cupo').check()
await page.getByRole('button', { name: 'Continuar' }).click()
await page.getByText('Caballeros · Suma 13').waitFor()
await shot(page, '61-step6-combinado-suma', true)
// Browser Back while the confirmation is in flight: the wizard stays mounted
let draftBody; let release; const gate = new Promise(r => { release = r })
await page.route('**/api/clubs/*/events/drafts', async route => {
  const response = await route.fetch(); draftBody = await response.json(); await gate; await route.fulfill({ response })
})
await page.getByRole('button', { name: 'Crear evento' }).click()
await page.locator('button[aria-busy="true"]').waitFor()
const before = page.url()
await page.goBack({ timeout: 3000 }).catch(() => {})
await page.waitForTimeout(800)
assert.equal(page.url(), before, 'URL kept while saving')
await page.getByText('Paso 6 de 6 · Revisión').waitFor({ timeout: 2000 })
await page.getByText('Mixto · 6ta + 6ta').waitFor({ timeout: 2000 })
assert.equal(await page.locator('button[aria-busy="true"]').count(), 1, 'save still in flight and the form mounted')
await shot(page, '62-step6-back-held-while-saving', true)
release()
await page.getByText('¡Creaste un evento!').waitFor()
await shot(page, '63-success-after-held-back')
await page.unroute('**/api/clubs/*/events/drafts')
// Navigation works again after the save
await page.goBack(); await page.waitForTimeout(800)
assert.notEqual(new URL(page.url()).pathname, '/club/events/new', 'browser Back works after the save')
console.log('after back', new URL(page.url()).pathname)
// API: no registration window, readable names, same category twice kept
assert.equal(draftBody.event.status, 'DRAFT'); assert.equal(draftBody.event.registrationOpenAt, null); assert.equal(draftBody.event.registrationCloseAt, null)
const names = draftBody.divisions.map(d => d.name).sort(); console.log('API names', names)
assert.deepEqual(names, ['Caballeros · Suma 13', 'Mixto · 6ta + 6ta'])
const twice = draftBody.divisions.find(d => d.criterion === 'COMBINADO')
assert.equal(twice.categoryCode, '6TA'); assert.equal(twice.secondCategoryCode, '6TA')
assert.equal((await db('select count(*)::int n from events where name=$1', [NAME]))[0].n, 1)
// Hub shows both; edit Combinado to 6ta + 7ma and back to 6ta + 6ta (name follows, API verified)
const hub = BASE + '/club/events/' + draftBody.event.id
const listed = page.waitForResponse(r => r.url().endsWith('/events/' + draftBody.event.id + '/divisions') && r.request().method() === 'GET')
await page.goto(hub)
const hubNames = (await (await listed).json()).map(d => d.name).sort(); assert.deepEqual(hubNames, names)
await page.getByText('Mixto · 6ta + 6ta').waitFor(); await page.getByText('Caballeros · Suma 13').waitFor()
await shot(page, '64-hub-combinado-same-twice', true)
async function editCombinado(fromTitle, b, expected) {
  await page.getByRole('button', { name: 'Editar ' + fromTitle }).click(); await page.waitForURL(/edit$/)
  assert.equal(await page.getByLabel(/Categoría A/).inputValue() !== '', true)
  await page.getByLabel(/Categoría B/).selectOption({ label: b })
  await page.getByRole('button', { name: 'Continuar' }).click()
  const patched = page.waitForResponse(r => r.request().method() === 'PATCH' && r.url().includes('/divisions/'))
  await page.getByRole('button', { name: /Guardar/ }).click()
  const body = await (await patched).json(); assert.equal(body.name, expected); console.log('PATCH name', body.name)
  await page.waitForURL(hub); await page.getByText(expected).first().waitFor()
}
await page.getByRole('button', { name: 'Editar Mixto · 6ta + 6ta' }).click(); await page.waitForURL(/edit$/)
assert.equal(await page.getByLabel(/Categoría B/).locator('option:checked').textContent(), '6ta')
await shot(page, '65-edit-combinado-same-twice', true)
await page.goto(hub)
await editCombinado('Mixto · 6ta + 6ta', '7ma', 'Mixto · 6ta + 7ma')
await editCombinado('Mixto · 6ta + 7ma', '6ta', 'Mixto · 6ta + 6ta')
// Custom name (set through the API, the wizard has no name field) is kept and shown
const suma = draftBody.divisions.find(d => d.criterion === 'SUMA')
await db('update divisions set name=$1 where id=$2', ['Suma libre de verano', suma.id])
await page.goto(hub); await page.getByText('Suma libre de verano').waitFor()
await shot(page, '66-hub-custom-name', true)
await page.getByRole('button', { name: 'Editar Suma libre de verano' }).click(); await page.waitForURL(/edit$/)
await page.getByLabel('Suma de categorías').fill('12'); await page.getByRole('button', { name: 'Continuar' }).click()
const patched = page.waitForResponse(r => r.request().method() === 'PATCH' && r.url().includes('/divisions/'))
await page.getByRole('button', { name: /Guardar/ }).click()
const kept = await (await patched).json(); assert.equal(kept.name, 'Suma libre de verano'); assert.equal(kept.sumTarget, 12)
// Direct load of /club/events/new: Back would leave the document, so the browser asks before unloading
const DIRECT = 'Copa Directa ' + (Date.now() % 100000)
await steps1to3(page, DIRECT)
await label(page, '5ta').click(); await page.getByRole('button', { name: 'Continuar' }).click()
await page.getByLabel('Máximo de parejas').fill('8'); await page.getByLabel('No, cerrar al completar cupo').check()
await page.getByRole('button', { name: 'Continuar' }).click(); await page.getByText('Caballeros · 5ta').waitFor()
let release2; const gate2 = new Promise(r => { release2 = r }); const dialogs = []
page.on('dialog', dialog => { dialogs.push(dialog.type()); void dialog.dismiss() })
await page.route('**/api/clubs/*/events/drafts', async route => { const response = await route.fetch(); await gate2; await route.fulfill({ response }) })
await page.getByRole('button', { name: 'Crear evento' }).click(); await page.locator('button[aria-busy="true"]').waitFor()
const direct = page.url()
await page.goBack({ timeout: 3000 }).catch(() => {}); await page.waitForTimeout(800)
assert.deepEqual(dialogs, ['beforeunload']); assert.equal(page.url(), direct)
await page.getByText('Caballeros · 5ta').waitFor({ timeout: 2000 })
release2(); await page.getByText('¡Creaste un evento!').waitFor()
assert.equal((await db('select count(*)::int n from events where name=$1', [DIRECT]))[0].n, 1)
await page.unroute('**/api/clubs/*/events/drafts')
console.log('ROUND2 OK')
await browser.close()
